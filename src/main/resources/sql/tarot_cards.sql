-- ============================================================
-- 塔罗牌数据库表 & 初始数据
-- 78 张牌：22 张大阿尔卡那 + 56 张小阿尔卡那
-- ============================================================

DROP TABLE IF EXISTS `tarot_cards`;

CREATE TABLE `tarot_cards` (
  `id`          BIGINT       NOT NULL AUTO_INCREMENT  COMMENT '主键',
  `name`        VARCHAR(50)  NOT NULL                 COMMENT '中文名',
  `name_en`     VARCHAR(100) NOT NULL                 COMMENT '英文名',
  `type`        ENUM('major','minor') NOT NULL        COMMENT '牌类型：major=大阿尔卡那, minor=小阿尔卡那',
  `suit`        ENUM('cups','wands','swords','pentacles') NULL COMMENT '花色（小阿尔卡那专用）',
  `card_number` TINYINT      NOT NULL                 COMMENT '牌序号（大牌 0-21，小牌 1-14）',
  `description` TEXT                                  COMMENT '牌面描述',
  `upright`     TEXT                                  COMMENT '正位含义',
  `reversed`    TEXT                                  COMMENT '逆位含义',
  `keywords`    VARCHAR(200)                          COMMENT '关键词，逗号分隔',
  `image_url`   VARCHAR(500)                          COMMENT '牌面图片 URL',
  `created_at`  DATETIME     DEFAULT CURRENT_TIMESTAMP,
  `updated_at`  DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_type_number_suit` (`type`, `card_number`, `suit`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='塔罗牌数据表';

